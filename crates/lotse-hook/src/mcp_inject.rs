//! The `lotse` MCP server, as each agent is told about it. Per pane only, like the status hooks:
//! nothing is written to `~/.claude`, `~/.codex` or `~/.config/opencode`.
//!
//! * Claude Code: `.mcp.json` at the root of the injected plugin directory (`${VAR}` expansion in
//!   `command` and `env`).
//! * Codex: a marked `[mcp_servers.lotse]` block in the `config.toml` of the mirrored `CODEX_HOME`
//!   (Codex does not expand variables: the hook binary's path is written out; `env_vars` forwards
//!   the pane's `LOTSE_*` variables, which Codex would otherwise filter out of an MCP server's
//!   environment).
//! * OpenCode: an `mcp.lotse` entry in the inline config `OPENCODE_CONFIG_CONTENT` of the pane
//!   (the overlay directory links the user's own `opencode.json`, which must not be edited).
//!
//! The server needs `LOTSE_SESSION_ID`, `LOTSE_PROJECT_ID`, `LOTSE_SOCKET` and `LOTSE_TOKEN_FILE`:
//! the socket and the *path* of the token file. The token itself never appears in a generated file,
//! an environment variable or an argument.
//!
//! **Unverified** against the real CLIs (no agent is run by tests): Claude's `${VAR}` expansion in a
//! plugin `.mcp.json` and the resulting tool-name prefix, Codex's `env_vars` / `tool_timeout_sec`
//! keys and its approval of MCP tool calls, OpenCode's `OPENCODE_CONFIG_CONTENT` and whether its
//! local MCP processes inherit the pane's environment.

use anyhow::{Context, Result};
use serde_json::{Value, json};
use std::path::Path;
use std::sync::Mutex;

/// The server's name in every agent's config (tools show up as `mcp__…lotse__<tool>` in Claude).
pub const SERVER_NAME: &str = "lotse";

/// Seconds an agent waits for a tool call: `start_session` waits for the user, `wait_session` for a child.
pub const TOOL_TIMEOUT_SECS: u64 = 3600;

/// The variables the server reads from the pane.
pub const ENV_NAMES: [&str; 4] = [
    "LOTSE_SESSION_ID",
    "LOTSE_PROJECT_ID",
    "LOTSE_SOCKET",
    "LOTSE_TOKEN_FILE",
];

pub fn claude_mcp_json() -> String {
    let env: serde_json::Map<String, Value> = ENV_NAMES
        .iter()
        .map(|name| ((*name).to_owned(), json!(format!("${{{name}:-}}"))))
        .collect();
    let config = json!({
        "mcpServers": {
            SERVER_NAME: {
                "type": "stdio",
                // the daemon exports LOTSE_HOOK_BIN into every pane, like for the status hooks
                "command": "${LOTSE_HOOK_BIN:-lotse-hook}",
                "args": ["mcp"],
                "env": env,
            }
        }
    });
    serde_json::to_string_pretty(&config).unwrap_or_default() + "\n"
}

/// Write `<plugin_dir>/.mcp.json` (a file that already matches is left alone).
pub fn ensure_claude(plugin_dir: &Path) -> Result<()> {
    write_if_changed(&plugin_dir.join(".mcp.json"), &claude_mcp_json()).map(|_| ())
}

/// Replace `path` atomically (a Claude or Codex starting right now never reads half a file);
/// `false` when it already holds `content`.
fn write_if_changed(path: &Path, content: &str) -> Result<bool> {
    // panes are created concurrently and share the temporary name
    static ONE_AT_A_TIME: Mutex<()> = Mutex::new(());
    let _guard = ONE_AT_A_TIME.lock().unwrap_or_else(|e| e.into_inner());
    if std::fs::read_to_string(path).is_ok_and(|have| have == content) {
        return Ok(false);
    }
    let dir = path.parent().context("config file without a directory")?;
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    let tmp = dir.join(format!(".mcp-tmp-{}", std::process::id()));
    std::fs::write(&tmp, content).with_context(|| format!("writing {}", tmp.display()))?;
    std::fs::rename(&tmp, path)
        .inspect_err(|_| {
            let _ = std::fs::remove_file(&tmp);
        })
        .with_context(|| format!("replacing {}", path.display()))?;
    Ok(true)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodexOutcome {
    Written,
    Unchanged,
    /// The user's own `config.toml` already defines `mcp_servers.lotse` (or cannot be read as TOML).
    Skipped,
}

const CODEX_BEGIN: &str = "# >>> lotse mcp (generated by Lotse, not part of your config)";
const CODEX_END: &str = "# <<< lotse mcp";

fn codex_block(hook_bin: &str) -> String {
    let string = |s: &str| toml::Value::String(s.to_owned()).to_string();
    let vars: Vec<String> = ENV_NAMES.iter().map(|n| string(n)).collect();
    format!(
        "{CODEX_BEGIN}\n[mcp_servers.{SERVER_NAME}]\ncommand = {}\nargs = [\"mcp\"]\ntool_timeout_sec = {TOOL_TIMEOUT_SECS}\nenv_vars = [{}]\n{CODEX_END}\n",
        string(hook_bin),
        vars.join(", "),
    )
}

/// `text` without our marked block.
fn without_codex_block(text: &str) -> String {
    match (text.find(CODEX_BEGIN), text.find(CODEX_END)) {
        (Some(from), Some(to)) if from < to => {
            let end = to + CODEX_END.len();
            let rest = text[end..].strip_prefix('\n').unwrap_or(&text[end..]);
            let head = text[..from].trim_end_matches('\n');
            match (head.is_empty(), rest.is_empty()) {
                (true, _) => rest.to_owned(),
                (false, true) => format!("{head}\n"),
                (false, false) => format!("{head}\n{rest}"),
            }
        }
        _ => text.to_owned(),
    }
}

/// Put the Lotse server into a mirrored `config.toml` (made when it is missing). The block is
/// replaced when the hook binary moved and added again when the mirror regenerated the file.
pub fn ensure_codex(config_toml: &Path, hook_bin: &str) -> Result<CodexOutcome> {
    let existing = match std::fs::read_to_string(config_toml) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(e).with_context(|| format!("reading {}", config_toml.display())),
    };
    let base = without_codex_block(&existing);
    let Ok(table) = base.parse::<toml::Table>() else {
        return Ok(CodexOutcome::Skipped);
    };
    let users_own = table
        .get("mcp_servers")
        .is_some_and(|servers| servers.get(SERVER_NAME).is_some());
    if users_own {
        return Ok(CodexOutcome::Skipped);
    }
    let mut next = base.trim_end_matches('\n').to_owned();
    if !next.is_empty() {
        next.push_str("\n\n");
    }
    next.push_str(&codex_block(hook_bin));
    if next.parse::<toml::Table>().is_err() {
        return Ok(CodexOutcome::Skipped);
    }
    Ok(if write_if_changed(config_toml, &next)? {
        CodexOutcome::Written
    } else {
        CodexOutcome::Unchanged
    })
}

/// The inline OpenCode config for the pane: `existing` (the pane's own `OPENCODE_CONFIG_CONTENT`)
/// with `mcp.lotse` added. `None`: leave the variable alone (not JSON, or the user has an
/// `mcp.lotse` of their own).
pub fn opencode_config_content(existing: Option<&str>, hook_bin: &str) -> Option<String> {
    let mut root = match existing.map(str::trim).filter(|s| !s.is_empty()) {
        None => serde_json::Map::new(),
        Some(text) => match serde_json::from_str::<Value>(text).ok()? {
            Value::Object(root) => root,
            _ => return None,
        },
    };
    let Value::Object(mcp) = root.entry("mcp").or_insert_with(|| json!({})) else {
        return None;
    };
    if mcp.contains_key(SERVER_NAME) {
        return None;
    }
    mcp.insert(
        SERVER_NAME.into(),
        json!({"type": "local", "command": [hook_bin, "mcp"], "enabled": true}),
    );
    serde_json::to_string(&root).ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::{Value, json};

    fn read(path: &Path) -> String {
        std::fs::read_to_string(path).unwrap()
    }

    #[test]
    fn claude_gets_a_stdio_server_that_runs_the_hook_binary_and_reads_the_pane_variables() {
        let v: Value = serde_json::from_str(&claude_mcp_json()).unwrap();
        let server = &v["mcpServers"]["lotse"];
        assert_eq!(server["command"], "${LOTSE_HOOK_BIN:-lotse-hook}");
        assert_eq!(server["args"], json!(["mcp"]));
        let env = server["env"].as_object().unwrap();
        for name in ENV_NAMES {
            assert_eq!(env[name], format!("${{{name}:-}}"), "{name}");
        }
        assert_eq!(env.len(), ENV_NAMES.len());
        assert!(
            server.get("type").is_none_or(|t| t == "stdio"),
            "stdio, no URL"
        );
        // only a path to the token, never a value
        let text = claude_mcp_json();
        assert!(!text.contains("LOTSE_TOKEN\""), "{text}");
    }

    #[test]
    fn ensure_claude_writes_once_and_repairs() {
        let tmp = tempfile::tempdir().unwrap();
        ensure_claude(tmp.path()).unwrap();
        let file = tmp.path().join(".mcp.json");
        assert_eq!(read(&file), claude_mcp_json());
        let before = std::fs::metadata(&file).unwrap().modified().unwrap();
        ensure_claude(tmp.path()).unwrap();
        assert_eq!(
            std::fs::metadata(&file).unwrap().modified().unwrap(),
            before
        );
        std::fs::write(&file, "{}").unwrap();
        ensure_claude(tmp.path()).unwrap();
        assert_eq!(read(&file), claude_mcp_json());
        assert_eq!(std::fs::read_dir(tmp.path()).unwrap().count(), 1);
    }

    fn parsed(path: &Path) -> toml::Table {
        read(path).parse().unwrap()
    }

    #[test]
    fn codex_block_is_added_once_next_to_the_users_config() {
        let tmp = tempfile::tempdir().unwrap();
        let cfg = tmp.path().join("config.toml");
        std::fs::write(
            &cfg,
            "model = \"gpt-5\"\n\n[mcp_servers.other]\ncommand = \"x\"\n",
        )
        .unwrap();
        assert_eq!(
            ensure_codex(&cfg, "/Applications/Lotse.app/lotse-hook").unwrap(),
            CodexOutcome::Written
        );
        let t = parsed(&cfg);
        assert_eq!(t["model"].as_str(), Some("gpt-5"));
        assert_eq!(t["mcp_servers"]["other"]["command"].as_str(), Some("x"));
        let lotse = &t["mcp_servers"]["lotse"];
        assert_eq!(
            lotse["command"].as_str(),
            Some("/Applications/Lotse.app/lotse-hook")
        );
        assert_eq!(lotse["args"].as_array().unwrap().len(), 1);
        assert_eq!(lotse["args"][0].as_str(), Some("mcp"));
        assert_eq!(
            lotse["tool_timeout_sec"].as_integer(),
            Some(TOOL_TIMEOUT_SECS as i64)
        );
        let vars: Vec<&str> = lotse["env_vars"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap())
            .collect();
        assert_eq!(vars, ENV_NAMES);
        assert!(!read(&cfg).to_lowercase().contains("token\""));

        let once = read(&cfg);
        assert_eq!(
            ensure_codex(&cfg, "/Applications/Lotse.app/lotse-hook").unwrap(),
            CodexOutcome::Unchanged
        );
        assert_eq!(read(&cfg), once);
    }

    #[test]
    fn codex_block_follows_a_moved_hook_binary_and_a_regenerated_config() {
        let tmp = tempfile::tempdir().unwrap();
        let cfg = tmp.path().join("config.toml");
        std::fs::write(&cfg, "model = \"a\"\n").unwrap();
        ensure_codex(&cfg, "/old/lotse-hook").unwrap();
        assert_eq!(
            ensure_codex(&cfg, "/new path/lotse-hook").unwrap(),
            CodexOutcome::Written
        );
        let t = parsed(&cfg);
        assert_eq!(
            t["mcp_servers"]["lotse"]["command"].as_str(),
            Some("/new path/lotse-hook")
        );
        assert_eq!(read(&cfg).matches("[mcp_servers.lotse]").count(), 1);
        // the mirror rewrote config.toml without our block
        std::fs::write(&cfg, "model = \"b\"\n").unwrap();
        assert_eq!(
            ensure_codex(&cfg, "/new path/lotse-hook").unwrap(),
            CodexOutcome::Written
        );
        assert_eq!(parsed(&cfg)["model"].as_str(), Some("b"));
        // no config.toml yet: one is made
        let fresh = tmp.path().join("fresh.toml");
        ensure_codex(&fresh, "/h/lotse-hook").unwrap();
        assert!(parsed(&fresh)["mcp_servers"]["lotse"].is_table());
    }

    #[test]
    fn codex_users_own_lotse_server_or_broken_config_is_left_alone() {
        let tmp = tempfile::tempdir().unwrap();
        let own = tmp.path().join("own.toml");
        let text = "[mcp_servers.lotse]\ncommand = \"mine\"\n";
        std::fs::write(&own, text).unwrap();
        assert_eq!(
            ensure_codex(&own, "/h/lotse-hook").unwrap(),
            CodexOutcome::Skipped
        );
        assert_eq!(read(&own), text);
        let broken = tmp.path().join("broken.toml");
        std::fs::write(&broken, "model = ").unwrap();
        assert_eq!(
            ensure_codex(&broken, "/h/lotse-hook").unwrap(),
            CodexOutcome::Skipped
        );
        assert_eq!(read(&broken), "model = ");
    }

    #[test]
    fn opencode_inline_config_adds_the_server_and_keeps_the_users_keys() {
        let v: Value =
            serde_json::from_str(&opencode_config_content(None, "/h/lotse-hook").unwrap()).unwrap();
        assert_eq!(v["mcp"]["lotse"]["type"], "local");
        assert_eq!(
            v["mcp"]["lotse"]["command"],
            json!(["/h/lotse-hook", "mcp"])
        );
        assert_eq!(v["mcp"]["lotse"]["enabled"], true);

        let existing = r#"{"theme":"x","mcp":{"other":{"type":"remote","url":"https://e"}}}"#;
        let v: Value = serde_json::from_str(
            &opencode_config_content(Some(existing), "/h/lotse-hook").unwrap(),
        )
        .unwrap();
        assert_eq!(v["theme"], "x");
        assert_eq!(v["mcp"]["other"]["url"], "https://e");
        assert_eq!(v["mcp"]["lotse"]["type"], "local");
        // empty or blank counts as unset
        assert!(opencode_config_content(Some("  "), "/h/lotse-hook").is_some());
    }

    #[test]
    fn opencode_inline_config_is_left_alone_when_it_is_not_ours_to_change() {
        for existing in [
            "not json",
            "[1]",
            r#"{"mcp":{"lotse":{"type":"local","command":["mine"]}}}"#,
            r#"{"mcp":"nope"}"#,
        ] {
            assert_eq!(
                opencode_config_content(Some(existing), "/h/lotse-hook"),
                None,
                "{existing}"
            );
        }
    }
}
